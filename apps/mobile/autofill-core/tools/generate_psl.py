#!/usr/bin/env python3
"""Generates PslData.kt from the Public Suffix List (https://publicsuffix.org, MPL-2.0).

Usage: python3 generate_psl.py public_suffix_list.dat > ../src/commonMain/kotlin/.../url/PslData.kt
Only ASCII rules are kept; hosts reaching the matcher are already punycode.
"""
import sys

rules = []
for line in open(sys.argv[1], encoding="utf-8"):
    line = line.strip()
    if not line or line.startswith("//"):
        continue
    rule = line.split()[0].lower()
    if all(ord(c) < 128 for c in rule):
        rules.append(rule)

CHUNK = 40_000  # stay well below the JVM 64 KB constant limit
chunks, current = [], []
size = 0
for r in rules:
    if size + len(r) + 1 > CHUNK:
        chunks.append("\n".join(current))
        current, size = [], 0
    current.append(r)
    size += len(r) + 1
if current:
    chunks.append("\n".join(current))

print("// Generated by tools/generate_psl.py from the Public Suffix List (MPL-2.0). Do not edit.")
print("package com.framepersecond.m3bitwarden.autofill.url")
print()
print("internal object PslData {")
print(f"    const val RULE_COUNT: Int = {len(rules)}")
print()
print("    fun chunks(): List<String> = listOf(")
for i, _ in enumerate(chunks):
    print(f"        CHUNK_{i},")
print("    )")
for i, c in enumerate(chunks):
    print()
    print(f"    private const val CHUNK_{i}: String = \"\"\"")
    print(c)
    print('"""')
print("}")
